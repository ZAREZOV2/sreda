import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import {fileURLToPath} from 'node:url';
import {spawnSync} from 'node:child_process';
import {createHash} from 'node:crypto';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const app=path.join(root,'app');
const pkg=JSON.parse(fs.readFileSync(path.join(app,'package.json'),'utf8'));
const version=pkg.version;
if(!/^\d+\.\d+\.\d+$/.test(version))throw Error('Expected a release version');
const release=path.join(root,'outputs','releases',version);
if(fs.existsSync(release))throw Error('This release already exists. Bump the version before publishing another build.');
const target=path.join(root,'work','build','cargo');
const stage=path.join(root,'work','release-check',version);
fs.mkdirSync(stage,{recursive:true});
const environment={...process.env,CARGO_TARGET_DIR:target};
const run=(command,args,options={})=>{
 const result=spawnSync(command,args,{cwd:app,env:environment,stdio:'inherit',...options});
 if(result.error)throw result.error;
 if(result.status!==0)throw Error(`${path.basename(command)} failed (${result.status})`);
};
run(process.execPath,[path.join(root,'scripts','build-frontend.mjs')]);
run(process.execPath,['--experimental-strip-types','--test',...fs.readdirSync(path.join(app,'tests')).filter(n=>n.endsWith('.test.ts')).map(n=>path.join(app,'tests',n))]);
const cargo=process.env.CARGO || path.join(os.homedir(),'.cargo','bin',process.platform==='win32'?'cargo.exe':'cargo');
const flags=['--release','--locked',...(process.env.SREDA_OFFLINE==='1'?['--offline']:[]),'--manifest-path',path.join(app,'src-tauri','Cargo.toml')];
run(cargo,['test',...flags,'--lib']);
run(cargo,['build',...flags]);
const executable=path.join(target,'release',process.platform==='win32'?'sreda-kanban.exe':'sreda-kanban');
const report=path.join(stage,'self-check.json');
// A copied executable, away from dist, with dev-server proxy variables removed.
const standalone=path.join(stage,path.basename(executable));
fs.copyFileSync(executable,standalone);
run(standalone,['--self-check',report],{cwd:stage});
const result=JSON.parse(fs.readFileSync(report,'utf8'));
if(!result.ok||!result.customProtocol||!result.sqliteRoundtrip)throw Error('Packaged executable self-check failed');
const publish=path.join(stage,`publish-${process.pid}`);
fs.mkdirSync(publish,{recursive:true});
const name=`Sreda-${version}${process.platform==='win32'?'.exe':''}`;
fs.copyFileSync(standalone,path.join(publish,name));
fs.copyFileSync(report,path.join(publish,'self-check.json'));
fs.writeFileSync(path.join(publish,'README.txt'),`Среда ${version}\n\nЗапустите ${name}. Интерфейс, Rust-бэкенд и SQLite включены в exe.\nNode.js, Vite и отдельный сервер для работы не нужны. Требуется WebView2.\nДанные: %LOCALAPPDATA%\\local.sreda.kanban — прежние доски сохраняются.\nИсходники: Sreda-${version}-Source.zip. Проверка упаковки: self-check.json.\n`);
const source=path.join(publish,`Sreda-${version}-Source.zip`);
run('powershell.exe',['-NoProfile','-ExecutionPolicy','Bypass','-File',path.join(root,'scripts','archive-source.ps1'),'-Destination',source],{cwd:root});
const sums=fs.readdirSync(publish).filter(n=>n!== 'SHA256SUMS.txt').map(n=>`${createHash('sha256').update(fs.readFileSync(path.join(publish,n))).digest('hex')}  ${n}`).join('\n');
fs.writeFileSync(path.join(publish,'SHA256SUMS.txt'),sums+'\n');
fs.mkdirSync(path.dirname(release),{recursive:true});
fs.renameSync(publish,release);
fs.writeFileSync(path.join(root,'outputs','releases','latest.txt'),version+'\n');
console.log(`Verified release: ${release}`);
